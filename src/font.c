/* The width of the widest line. */
s32 frmFontGetWidth(TextFrame *f) {
    u8 *p = TEXT(f);
    s32 c;
    s32 w = 0;
    s32 max = 0;
    s32 i;

    for (c = *p; c != '\0'; c = *++p) {
        i = (u8) c - ' ';
        if (i < 0) {
            if (max < w) {
                max = w;
            }
            w = 0;
        } else if (i == '#' - ' ') {
            /* The bytes compared (u8) put the '#' register first (IDO_NOTES 192). */
            while (*++p != '\0' && *p != '#') {
            }
        } else {
            w += f->xgap + (f32) gFontGlyphWidths[i] * f->w / 8;
        }
    }
    if (max < w) {
        max = w;
    }
    return max;
}

/* The height: a cell, and a cell and a gap for each '\n'. */
s32 frmFontGetHeight(TextFrame *f) {
    u8 *p = TEXT(f);
    s32 h = f->h;

    for (; *p != '\0'; p++) {
        if (*p == '\n') {
            h += f->ygap + f->h;
        }
    }
    return h;
}
