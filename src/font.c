/* One glyph at (x, y), w x h: an 8x12 4-bit tile and a texture rectangle, at a quarter pixel.
 * The steps (ds, dt) are computed at the top with ix and iy: that work before the commands moves
 * where uopt starts the rectangle's values, so the LoadSync pointer takes v0 as in the game. */
Gfx *frmFontDrawGlyph(Gfx *gfx, f32 x, f32 y, s32 w, s32 h, u8 *glyph) {
    s32 ix = x * 4.0f + 0.5f;
    s32 iy = y * 4.0f + 0.5f;
    s32 ds = 0x2000 / w;
    s32 dt = 0x3000 / h;

    gDPPipeSync(gfx++);
    gDPLoadTextureTile_4b(gfx++, glyph, G_IM_FMT_I, 8, 12, 0, 0, 7, 11, 0, G_TX_CLAMP, G_TX_CLAMP,
                          3, 4, G_TX_NOLOD, G_TX_NOLOD);
    gSPTextureRectangle(gfx++, ix, iy, ix + w * 4, iy + h * 4, G_TX_RENDERTILE,
                        (s32) (x * 32.0f - ix * 8), (s32) (y * 32.0f - iy * 8), ds, dt);
    gSPEndDisplayList(gfx);
    return gfx;
}

/* A hex digit's value (0 for anything else). */
s32 frmFontHexDigit(u8 c) {
    if (c >= '0' && c <= '9') {
        return c - '0';
    }
    c &= ~0x20;
    if (c >= 'A' && c <= 'F') {
        return c - 'A' + 10;
    }
    return 0;
}

/* Draws the text.
 * Matched 2026-10-04; it was parked for its registers: the character sat in a0 where the game
 * has v1, and the index's andi in v0 where the game computes it in place, into i's own t0.
 * The draw is the default's own code; the accent cases `goto draw` back into it, and '#' comes
 * before '\n', as the game lays them out. The advance converts the width byte to float on its
 * own and divides by 8 ("(f32) gFontGlyphWidths[i] * f->w / 8"), as the game does.
 * The two marked FAKEs, what the original must have had:
 * - "c = i;", a dead store to c between the index and its "i >= 0" test: uopt tests i itself
 *   (the game's in-place "andi t0; addiu t0; bltzl t0") only when c changes in between
 *   (IDO_NOTES 278); without it uopt copy-propagates the expression into the test and gives it
 *   a register of its own. Its reader was not compiled in this build.
 * - "c * 1" in the '#' loop: uopt orders a compare at entry, a variable before a constant and an
 *   operation after one, so the plain "c != '#'" comes out "c, '#'" where the game has "'#', c".
 *   The original's left side was an operation that uopt folds (a macro or cast around c). */
Gfx *frmFontDrawText(Gfx *gfx, TextFrame *f) {
    f32 x = f->x;
    f32 y = f->y;
    u8 *p = TEXT(f);
    s32 c;
    s32 i;
    s32 r, g, b;

    for (c = *p; c != '\0'; c = *++p) {
        switch (c) {
            default:
                i = (u8) c - ' ';
                c = i; /* FAKE: a dead store (c is read again only after the step) */
                if (i >= 0) {
                draw:
                    gfx = frmFontDrawGlyph(gfx, x, y, f->w, f->h, gFontGlyphs[i]);
                    x += f->xgap + (f32) gFontGlyphWidths[i] * f->w / 8;
                    continue;
                }
                continue;
            case '#':
                r = frmFontHexDigit(p[1]) * 0x11;
                g = frmFontHexDigit(p[2]) * 0x11;
                b = frmFontHexDigit(p[3]) * 0x11;
                gDPSetEnvColor(gfx++, r, g, b, 0xFF);
                while ((c = *++p) != '\0' && c * 1 != '#') { /* FAKE: "* 1" */
                }
                continue;
            case '\n':
                x = f->x;
                y += f->h + f->ygap;
                continue;
            case '<':
                switch (*++p) {
                    case 'a':
                        i = 0x60;
                        break;
                    case 'A':
                        i = 0x72;
                        break;
                    case 'e':
                        i = 0x64;
                        break;
                    case 'E':
                        i = 0x76;
                        break;
                    default:
                        continue;
                }
                goto draw;
            case '>':
                switch (*++p) {
                    case 'a':
                        i = 0x61;
                        break;
                    case 'A':
                        i = 0x73;
                        break;
                    case 'e':
                        i = 0x65;
                        break;
                    case 'E':
                        i = 0x77;
                        break;
                    case 'u':
                        i = 0x6E;
                        break;
                    case 'U':
                        i = 0x80;
                        break;
                    default:
                        continue;
                }
                goto draw;
            case '~':
                switch (*++p) {
                    case 'a':
                        i = 0x62;
                        break;
                    case 'A':
                        i = 0x74;
                        break;
                    case 'e':
                        i = 0x67;
                        break;
                    case 'E':
                        i = 0x79;
                        break;
                    case 'i':
                        i = 0x69;
                        break;
                    case 'I':
                        i = 0x7B;
                        break;
                    case 'o':
                        i = 0x6B;
                        break;
                    case 'O':
                        i = 0x7D;
                        break;
                    case 'u':
                        i = 0x6D;
                        break;
                    case 'U':
                        i = 0x7F;
                        break;
                    default:
                        continue;
                }
                goto draw;
            case '^':
                switch (*++p) {
                    case 'a':
                        i = 0x63;
                        break;
                    case 'A':
                        i = 0x75;
                        break;
                    case 'e':
                        i = 0x66;
                        break;
                    case 'E':
                        i = 0x78;
                        break;
                    case 'i':
                        i = 0x68;
                        break;
                    case 'I':
                        i = 0x7A;
                        break;
                    case 'o':
                        i = 0x6A;
                        break;
                    case 'O':
                        i = 0x7C;
                        break;
                    case 'u':
                        i = 0x6C;
                        break;
                    case 'U':
                        i = 0x7E;
                        break;
                    default:
                        continue;
                }
                goto draw;
            case '{':
                switch (*++p) {
                    case 'c':
                        i = 0x6F;
                        break;
                    case 'C':
                        i = 0x81;
                        break;
                    case 'e':
                        i = 0x70;
                        break;
                    case 'E':
                        i = 0x82;
                        break;
                    case 'b':
                        i = 0x71;
                        break;
                    default:
                        continue;
                }
                goto draw;
        }
    }
    return gfx;
}

/* The kind's draw: the render setup, the filter, the colour, then the text. */
Gfx *frmFontDraw(Gfx *gfx, TextFrame *f) {
    if (f->text == 0) {
        return gfx;
    }
    gSPDisplayList(gfx++, gFontSetupDl);
    if (f->flags & 1) {
        gDPSetTextureFilter(gfx++, G_TF_BILERP);
    } else {
        gDPSetTextureFilter(gfx++, G_TF_POINT);
    }
    gDPSetEnvColor(gfx++, f->r, f->g, f->b, f->a);
    return frmFontDrawText(gfx, f);
}

/* Text at (x, y) under parent: an 8x12 cell, gaps of 1 and 2, white, filtered. */
TextFrame *frmFontCreate(Frame *parent, s16 x, s16 y, char *text) {
    TextFrame *f = (TextFrame *) frmCreate(parent, gFrmKindFont);

    if (f == NULL) {
        return NULL;
    }
    f->flags |= 1;
    f->x = x;
    f->y = y;
    f->text = (u32) text;
    f->w = 8;
    f->h = 12;
    f->xgap = 1;
    f->ygap = 2;
    f->r = 0xFF;
    f->g = 0xFF;
    f->b = 0xFF;
    f->a = 0xFF;
    f->base = fileMappedAddr();
    return f;
}

Frame *frmFontDestroy(TextFrame *f) {
    return frmDestroy((Frame *) f);
}

/* Makes the kind (100 frames), and deletes it. */
s32 frmFontNewKind(void) {
    gFrmKindFont = frmNewKind("font ", (FrameDraw) frmFontDraw,
                                        sizeof(TextFrame), 100, NULL);
    PRINTF("FRM_Font を作成\n");
    if (gFrmKindFont == -1) {
        return -1;
    }
    return 0;
}

