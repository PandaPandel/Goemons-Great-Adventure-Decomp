/* 0xE8: its end: a count (0: forever), then a transposition (semitones) and a detune (1/32s)
 * added on each pass. Done, both are cleared and the loop falls through.
 * The game compares "beql field, count". uopt orders the operands of the pass test itself,
 * whatever the source order: a plain variable goes first. So in the original the count side of
 * that test was not the plain variable but an expression IDO folds only after uopt (as "^ 0"
 * is), used in that test alone. */
void sndCmdLoopEnd(void) {
    s32 count;

    count = *gSndCmdPtr++;
    gSndCurTrack->loopPass++;
    /* FAKE: `count ^ 0` is `count`; it puts the pass test's operands in the original's order. */
    if (count == 0 || (count ^ 0) != gSndCurTrack->loopPass) {
        gSndCurTrack->loopVelocity += (s8) *gSndCmdPtr++;
        gSndCurTrack->loopDetune += (s8) *gSndCmdPtr++ * 8;
        gSndCmdPtr = gSndCurTrack->loopStart;
        return;
    }
    gSndCurTrack->loopDetune = gSndCurTrack->loopVelocity = 0;
    gSndCmdPtr += 2;
}

