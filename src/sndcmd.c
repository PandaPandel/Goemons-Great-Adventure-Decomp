/* 0xF1: the track plays by the game's state (gSndGroupMusicId) against the sound id's low byte: mode
 * 1 mutes it while the state is below, mode 2 while above. Mode 0 marks a change of state
 * (gSndGroupMusicChanged) and unmutes every music track. The id's low byte is read as a byte (lbu 3).
 * One variable serves as the mode and the loop index (a separate index took a0 and moved the
 * command pointer's address to a1). In mode 0 the state is read as an array element: as a plain
 * u8 IDO evaluates it before the id byte (the original's state/changed pair is likely u8[2]). */
void sndCmdStateMute(void) {
    s32 i;

    i = (u8) (*gSndCmdPtr++ & 3);
    if (i != 0) {
        if (i == 1) {
            if ((u8) gSndCurTrack->id < gSndGroupMusicId) {
                gSndCurTrack->stateMuted = 0;
                return;
            }
            gSndCurTrack->stateMuted = 1;
            return;
        }
        if (gSndGroupMusicId < (u8) gSndCurTrack->id) {
            gSndCurTrack->stateMuted = 0;
            return;
        }
        gSndCurTrack->stateMuted = 1;
        return;
    }
    if ((u8) gSndCurTrack->id != ((u8 *) &gSndGroupMusicId)[0]) {
        gSndGroupMusicChanged = 1;
    }
    for (i = 0; i < SND_TRACKS; i++) {
        gSndTracks[i].stateMuted = 0;
    }
}

