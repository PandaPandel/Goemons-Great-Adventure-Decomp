/* 0xF9: a random variation: a group, then a chance (in 256ths). While fewer than 4 are queued,
 * and (on tracks 6-9) while no track has a volume scale sounding, a number is drawn from the noise
 * table, a counter and the tick count. If it beats the chance, one of the group's 8 variations
 * is picked, never the same one twice running, and queued with the track's slides.
 * The counter is incremented in place and read back ("gSndNoiseCounter++; i =
 * gSndNoiseCounter & 0x7F;"): IDO forwards the store, so the +1 stays a temp, the read-back value is
 * the game's t0 and the one index i steps in place in v0. The sum is built in r in three
 * statements, "r = T[i] << 8; r += T[i]; r = r + ...;", as the game's registers show. */
void sndCmdRandomVariation(void) {
    u8 group;
    u8 chance;
    u16 r;
    u8 pick;
    s32 i;

    group = *gSndCmdPtr++;
    chance = 0xFF - *gSndCmdPtr++;
    if (gSndSpawnCount < 4) {
        if (gSndCurTrackIndex >= 6 && gSndCurTrackIndex < 10) {
            for (i = 0; i < 18; i++) {
                if (gSndTracks[i].id != 0 && gSndTracks[i].stopFadeLevel != 0) {
                    return;
                }
            }
        }
        gSndNoiseCounter++;
        i = gSndNoiseCounter & 0x7F;
        r = gSndNoiseTable[i] << 8;
        i = (i + 1) & 0x7F;
        r += gSndNoiseTable[i];
        r = r + (gSndNoiseCounter >> 7) + (gSndTicks >> 1);
        if ((r & 0xFF) >= chance) {
            pick = (r >> 8) & 7;
            if (group == gSndLastVariationGroup && pick == gSndLastVariationPick) {
                pick = (pick + 1) & 7;
            }
            gSndLastVariationGroup = group;
            gSndLastVariationPick = pick;
            gSndSpawnQueue[gSndSpawnCount].r = r;
            gSndSpawnQueue[gSndSpawnCount].lim = &gSndVariationTable[group][pick];
            gSndSpawnQueue[gSndSpawnCount].sound = gSndCurTrack->id >> 16;
            for (i = 0; i < 3; i++) {
                gSndSpawnQueue[gSndSpawnCount].slideTarget[i] = gSndCurTrack->slideTarget[i];
                gSndSpawnQueue[gSndSpawnCount].slide[i] = gSndCurTrack->slide[i];
                gSndSpawnQueue[gSndSpawnCount].slideStep[i] = gSndCurTrack->slideStep[i];
                gSndSpawnQueue[gSndSpawnCount].slideTicks[i] = gSndCurTrack->slideTicks[i];
            }
            gSndSpawnCount++;
        }
    }
}

