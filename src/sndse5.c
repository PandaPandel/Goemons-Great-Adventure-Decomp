typedef struct SndSe {
    /* 0x0 */ u8 prio;  /* low 5 bits: priority */
    /* 0x1 */ u8 flags; /* high nibble: track - 15 */
    /* 0x2 */ u8 pad2[2];
    /* 0x4 */ u8 *data; /* the commands of its channel, or (several channels) their list */
} SndSe; /* size 0x8 */

typedef struct SndJingle {
    /* 0x0 */ u8 count;
    /* 0x1 */ u8 bank;
    /* 0x2 */ u8 pad2[2];
    /* 0x4 */ u8 **channels;
} SndJingle; /* size 0x8 */

