#define FX(obj) ((void *) ((u32) (obj) + sizeof(Obj)))

/* The logos' task. */
s32 logoProc(Obj *obj, s16 msg, void *arg) {
    DLFrame **frame = FX(obj);
    u16 pressed;
    s32 i;

    switch (msg) {
        case 2:
            *frame = (DLFrame *) frmCreate(gFrmLayers[0], gFrmKindDlist);
            osViSetSpecialFeatures(6);
            sndCommand(1);
            gLogoRunning = 1;
            gLogoFirstTimer = 0;
            gLogoFirstState = 0;
            gLogoFirstAlpha = 0;
            gLogoSecondTimer = 0;
            gLogoSecondState = 0;
            gLogoSecondAlpha = 0;
            break;
        case 1:
            frmDestroy(&(*frame)->f);
            break;
        case 0:
            pressed = 0;
            for (i = 0; i < 4; i++) {
                if ((*joyGetHeldTime)(i, START_BUTTON | A_BUTTON) == 1) {
                    pressed |= 0x1000;
                }
            }
            if (pressed & 0x1000) {
                if (gLogoFirstState <= 0) {
                    gLogoFirstState = 1;
                    gLogoSecondState = 0;
                } else if (gLogoFirstState < 2) {
                    if (gLogoFirstTimer >= 0x15) {
                        gLogoFirstState = 3;
                        gLogoSecondState = 2;
                    }
                } else if (gLogoSecondState == 2) {
                    gLogoSecondState = 3;
                }
            }
            logoUpdateFirst();
            logoUpdateSecond();
            break;
        case 3:
            if (*frame != NULL) {
                (*frame)->dl = gGfxDlHead;
                gGfxDlHead = logoDraw(gGfxDlHead);
                gSPEndDisplayList(gGfxDlHead++);
            }
            break;
    }
    return tskDefaultProc(obj, msg, arg);
}

/* 1 once the logos are over. */
s32 logoIsDone(s32 unused) {
    if (gLogoRunning == 0) {
        return 1;
    }
    return 0;
}

/* The first logo: fades in by 12, holds for 168 steps, fades out by 9, then starts the
 * second. */
void logoUpdateFirst(void) {
    switch (gLogoFirstState) {
        case 0:
            gLogoFirstDrawn = 1;
            gLogoFirstAlpha += 12;
            if (gLogoFirstAlpha >= 0xF1) {
                gLogoFirstAlpha = 0xFF;
                gLogoFirstState++;
            }
            gLogoFirstTimer = 0;
            break;
        case 1:
            gLogoFirstDrawn = 1;
            gLogoFirstTimer++;
            gLogoFirstAlpha = 0xFF;
            gLogoBackdropDrawn = 1;
            if (gLogoFirstTimer >= 0xA9) {
                gLogoFirstState++;
                gLogoFirstTimer = 0;
            }
            break;
        case 2:
            gLogoFirstDrawn = 1;
            gLogoFirstTimer++;
            gLogoFirstAlpha -= 9;
            if (gLogoFirstAlpha < 10) {
                gLogoFirstAlpha = 0;
                gLogoFirstState++;
                gLogoSecondState = 1;
            }
            break;
        case 3:
            gLogoFirstDrawn = 0;
            break;
        default:
            gLogoFirstDrawn = 0;
            break;
    }
}

/* The second logo: fades in by 3, holds for 96 steps, fades out by 12, then ends the
 * logos. */
void logoUpdateSecond(void) {
    switch (gLogoSecondState) {
        case 0:
            gLogoSecondDrawn = 0;
            break;
        case 1:
            gLogoSecondDrawn = 1;
            gLogoSecondAlpha += 3;
            if (gLogoSecondAlpha >= 0xF1) {
                gLogoSecondAlpha = 0xFF;
                gLogoSecondState++;
            }
            gLogoSecondTimer = 0;
            break;
        case 2:
            gLogoSecondDrawn = 1;
            gLogoSecondAlpha = 0xFF;
            gLogoSecondTimer++;
            gLogoBackdropDrawn = 1;
            if (gLogoSecondTimer >= 0x61) {
                gLogoSecondState++;
            }
            break;
        case 3:
            gLogoSecondDrawn = 1;
            gLogoSecondAlpha -= 12;
            if (gLogoSecondAlpha < 10) {
                gLogoSecondAlpha = 0;
                gLogoSecondState++;
            }
            gLogoSecondTimer = 0;
            break;
        case 4:
            gLogoRunning = 0;
            sndCommand(1);
            break;
    }
}

/* The logos' list, after the backdrop. */
Gfx *logoDraw(Gfx *gfx) {
    gLogoGfx = gfx;
    if (gLogoBackdropDrawn == 1) {
        logoDrawSprites(gLogoBackdropTexTable, gLogoBackdropTlut, gLogoBackdropRects, 0xFF);
    }
    if (gLogoFirstDrawn == 1) {
        logoDrawSprites(gLogoFirstTexTable, gLogoFirstTlut, gLogoFirstRects,
                               gLogoFirstAlpha);
    }
    if (gLogoSecondDrawn == 1) {
        logoDrawSprites(gLogoSecondTexTable, gLogoSecondTlut, gLogoSecondRects,
                               gLogoSecondAlpha);
    }
    return gLogoGfx;
}

/* Draws a sprite list at an alpha. */
void logoDrawSprites(LogoTex *tex, u16 *tlut, LogoRect *rect, u8 alpha) {
    s32 pad;
    s32 x0;
    s32 y0;
    s32 x1;
    s32 y1;

    gSPDisplayList(gLogoGfx++, gLogoSpriteSetupDl);
    gDPSetPrimColor(gLogoGfx++, 0, 0, 255, 255, 255, alpha);
    gDPLoadTLUT_pal256(gLogoGfx++, tlut);
    while (TRUE) {
        if (rect->flags & 0x10) {
            gDPLoadTextureBlock(gLogoGfx++, tex->addr, G_IM_FMT_CI, G_IM_SIZ_8b, tex->w, tex->h,
                                0, G_TX_MIRROR, G_TX_MIRROR, 9, 9, G_TX_NOLOD, G_TX_NOLOD);
            tex++;
        }
        x0 = rect->x << 2;
        y0 = rect->y << 2;
        x1 = (rect->x + rect->w) << 2;
        y1 = (rect->y + rect->h) << 2;
        x0 = x0;
        y0 = y0;
        gSPTextureRectangle(gLogoGfx++, x0, y0, x1, y1, G_TX_RENDERTILE, rect->s, rect->t,
                            1 << 10, 1 << 10);
        if (rect->flags >= 0x80) {
            break;
        }
        rect++;
    }
}
